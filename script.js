let currentLang = "en";

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key] !== undefined) el.innerHTML = translations[lang][key];
  });
  const toggle = document.getElementById("langToggle");
  if (toggle) {
    toggle.textContent = lang === "en" ? "FR" : "EN";
    toggle.setAttribute("aria-label", lang === "en" ? "Passer le site en français" : "Switch website to English");
  }
  localStorage.setItem("portfolio-lang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const saved = localStorage.getItem("portfolio-lang");
  applyLanguage(saved === "fr" ? "fr" : "en");

  document.getElementById("langToggle")?.addEventListener("click", () => {
    applyLanguage(currentLang === "en" ? "fr" : "en");
  });

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) entry.target.classList.add("visible");
    });
  }, { threshold: 0.12 });

  document.querySelectorAll(".reveal").forEach((el) => observer.observe(el));
});
// --- Gestion du Menu Mobile ---
const mobileToggle = document.getElementById("mobileToggle");
const navMenu = document.querySelector(".nav nav");
const navLinks = document.querySelectorAll(".nav nav a");

if (mobileToggle && navMenu) {
  mobileToggle.addEventListener("click", () => {
    mobileToggle.classList.toggle("is-active");
    navMenu.classList.toggle("is-open");
    // Bloque le scroll de la page quand le menu est ouvert
    document.body.style.overflow = navMenu.classList.contains("is-open") ? "hidden" : "";
  });

  // Ferme le menu dès qu'on clique sur un lien (vers une section)
  navLinks.forEach(link => {
    link.addEventListener("click", () => {
      mobileToggle.classList.remove("is-active");
      navMenu.classList.remove("is-open");
      document.body.style.overflow = ""; // Réactive le scroll
    });
  });
}